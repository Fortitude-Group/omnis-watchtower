// Generates src/plugin/core/data/popular-npm.ts and popular-pypi.ts (research R10). Maintainer
// script: run at release time, never at runtime.
// Usage: node scripts/build-popular-lists.mjs [npm|pypi]   (no argument builds both)
//
// npm: candidates come from npm-high-impact (MIT); unscoped names are ranked by last-week downloads
// via the bulk endpoint. Scoped names are skipped: the bulk endpoint rejects them, and a scope
// cannot be squatted without owning the org, so they add little to typosquat detection.
//
// PyPI: Hugo van Kemenade's top-pypi-packages monthly dump, licensed CC BY 4.0 (confirmed by the
// maintainer in hugovk/top-pypi-packages#78). We keep project names only, PEP 503-normalised, and
// the generated file carries the attribution the licence asks for.
import { writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dataDir = join(root, 'src', 'plugin', 'core', 'data')
const KEEP = 5000

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const today = () => new Date().toISOString().slice(0, 10)
const quote = (n) => `  ${JSON.stringify(n).replace(/^"|"$/g, "'")}`

const getJson = async (url) => {
  for (let attempt = 0; attempt < 6; attempt++) {
    const res = await fetch(url)
    if (res.status === 429 || res.status >= 500) {
      await sleep(2000 * 2 ** attempt)
      continue
    }
    if (!res.ok) throw new Error(`${url} -> ${res.status}`)
    return res.json()
  }
  throw new Error(`${url}: gave up after retries`)
}

const writeList = async (file, exportName, header, names) => {
  const out = join(dataDir, file)
  const body = `export const ${exportName}: readonly string[] = [\n${names.map(quote).join(',\n')}\n]\n`
  await writeFile(out, `${header.join('\n')}\n\n${body}`)
  console.log(`wrote ${names.length} names to ${out}`)
}

const buildNpm = async () => {
  const TOP_URL = 'https://cdn.jsdelivr.net/npm/npm-high-impact/lib/top.js'
  const PKG_URL = 'https://cdn.jsdelivr.net/npm/npm-high-impact/package.json'
  const BULK = 'https://api.npmjs.org/downloads/point/last-week/'
  const BATCH = 100
  const GAP_MS = 1100

  const topText = await (await fetch(TOP_URL)).text()
  const version = (await getJson(PKG_URL)).version
  const all = [...topText.matchAll(/'([^']+)'/g)].map((m) => m[1])
  const unscoped = [...new Set(all.filter((n) => !n.startsWith('@')))]
  console.log(`${all.length} candidates, ${unscoped.length} unscoped (scoped skipped)`)

  const downloads = new Map()
  for (let i = 0; i < unscoped.length; i += BATCH) {
    const batch = unscoped.slice(i, i + BATCH)
    const body = await getJson(BULK + batch.join(','))
    // A single-name batch returns the point object itself; larger batches return a map of them.
    const rows = batch.length === 1 ? { [batch[0]]: body } : body
    for (const n of batch) downloads.set(n, rows[n]?.downloads ?? 0)
    console.log(`ranked ${Math.min(i + BATCH, unscoped.length)}/${unscoped.length}`)
    await sleep(GAP_MS)
  }

  const ranked = unscoped
    .map((n, idx) => ({ n, d: downloads.get(n) ?? 0, idx }))
    .sort((a, b) => b.d - a.d || a.idx - b.idx)
    .slice(0, KEEP)
    .map((r) => r.n.toLowerCase())

  await writeList('popular-npm.ts', 'popularNpm', [
    '// GENERATED by scripts/build-popular-lists.mjs. Do not edit by hand.',
    `// Source: npm-high-impact@${version} (https://github.com/wooorm/npm-high-impact), licence MIT.`,
    '// Ranked by weekly downloads (https://api.npmjs.org/downloads/point/last-week), unscoped names only.',
    `// Generated: ${today()}. ${ranked.length} names, most popular first.`,
  ], ranked)
}

const buildPypi = async () => {
  const URL = 'https://hugovk.dev/top-pypi-packages/top-pypi-packages.min.json'
  const dump = await getJson(URL)
  if (!Array.isArray(dump.rows) || dump.rows.length < KEEP) throw new Error(`${URL}: expected at least ${KEEP} rows`)

  // PEP 503 normalisation; the dump is already ranked by downloads, most first.
  const seen = new Set()
  const names = []
  for (const row of dump.rows) {
    const n = String(row.project).toLowerCase().replace(/[-_.]+/g, '-')
    if (seen.has(n)) continue
    seen.add(n)
    names.push(n)
    if (names.length === KEEP) break
  }

  await writeList('popular-pypi.ts', 'popularPypi', [
    '// GENERATED by scripts/build-popular-lists.mjs. Do not edit by hand.',
    '// Source: "top-pypi-packages" by Hugo van Kemenade, https://github.com/hugovk/top-pypi-packages',
    '// (DOI: https://zenodo.org/badge/latestdoi/116806538).',
    '// Licence: CC BY 4.0, https://creativecommons.org/licenses/by/4.0/ (hugovk/top-pypi-packages#78).',
    `// Changes: project names only, download counts dropped, PEP 503-normalised, first ${KEEP} rows.`,
    `// Dump last updated ${dump.last_update}. Generated: ${today()}. ${names.length} names, most downloaded first.`,
  ], names)
}

const only = process.argv[2]
if (only && only !== 'npm' && only !== 'pypi') throw new Error(`unknown list "${only}" (use npm or pypi)`)
if (!only || only === 'pypi') await buildPypi()
if (!only || only === 'npm') await buildNpm()
