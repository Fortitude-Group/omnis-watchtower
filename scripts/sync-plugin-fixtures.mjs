// Copies a few recorded packages into src/plugin/tests/fixtures/http.ts. Engine tests
// (`claude plugin test`) may only import files inside the plugin folder, so they can't reach
// tests/fixtures/ directly. Run after scripts/record-fixtures.mjs: node scripts/sync-plugin-fixtures.mjs
import { writeFileSync } from 'node:fs'

const PACKAGES = ['npm/chalk', 'npm/react-dom-utilz', 'npm/crossenv', 'npm/zod', 'pypi/requests', 'pypi/reqeusts']
const merged = {}
for (const p of PACKAGES) Object.assign(merged, (await import(`../tests/fixtures/http/${p}.ts`)).fixtures)

const lines = Object.entries(merged).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
writeFileSync('src/plugin/tests/fixtures/http.ts', [
  '// Generated by scripts/sync-plugin-fixtures.mjs from tests/fixtures/http. Do not edit by hand.',
  `// Packages: ${PACKAGES.join(', ')}`,
  'export const recorded: Record<string, { status: number; body: unknown }> = {',
  ...lines,
  '}',
  '',
].join('\n'))
console.log(`wrote ${lines.length} fixtures`)
