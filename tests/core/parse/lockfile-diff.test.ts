describe('npm manifests', () => {
  test('manifestDeps reads every dependency section', () => {
    const deps = manifestDeps('package.json', packageJson)
    expect(deps.map((d) => d.name).sort()).toEqual([...LOCKED, ...NEW].sort())
    expect(deps.find((d) => d.name === 'aliased')!.ref).toEqual({ ecosystem: 'npm', name: 'real-pkg', version: '^2' })
    expect(deps.find((d) => d.name === 'local')!.ref).toBeUndefined()
  })

  test.each([
    ['package-lock.json', packageLock],
    ['pnpm-lock.yaml', pnpmLock],
    ['yarn.lock', yarnV1],
    ['yarn.lock', yarnBerry],
    ['bun.lock', bunLock],
  ])('%s: only unlocked declared deps are returned', (path, text) => {
    for (const n of LOCKED) expect(lockedNames(path, text).has(n)).toBe(true)
    const diff = lockfileDiff([{ path: 'package.json', text: packageJson }], [{ path, text }])
    expect(names(diff)).toEqual(NEW)
    expect(diff.unchecked).toEqual([])
  })

  test('package-lock nested and pnpm legacy keys are read', () => {
    expect(lockedNames('package-lock.json', packageLock).has('nested')).toBe(true)
    expect(lockedNames('pnpm-lock.yaml', pnpmLock).has('legacy')).toBe(true)
    expect(lockedNames('yarn.lock', yarnBerry).has('__metadata')).toBe(false)
  })

  test('no lockfile returns every declared dep; non-registry ones are unchecked', () => {
    const diff = lockfileDiff([{ path: 'package.json', text: packageJson }], [])
    expect(names(diff)).toEqual(['@scope/util', 'chalk', 'left-pad', 'new-dev-dep', 'new-opt', 'real-pkg', 'vitest'])
    expect(diff.unchecked.sort()).toEqual(['gh@github:a/b', 'local@file:../local'])
  })

  test('a lockfile of the other ecosystem does not count', () => {
    const diff = lockfileDiff([{ path: 'package.json', text: packageJson }], [{ path: 'uv.lock', text: '' }])
    expect(diff.packages).toHaveLength(7)
  })

  test('versions from the manifest are kept', () => {
    const diff = lockfileDiff([{ path: 'package.json', text: packageJson }], [{ path: 'package-lock.json', text: packageLock }])
    expect(diff.packages).toContainEqual({ ecosystem: 'npm', name: 'new-dev-dep', version: '^1.0.0' })
    expect(diff.packages).toContainEqual({ ecosystem: 'npm', name: 'new-opt' })
  })

  test('an unparseable package.json is unchecked', () => {
    expect(lockfileDiff([{ path: 'package.json', text: '{ nope' }], []).unchecked).toEqual(['package.json (unparseable)'])
  })
})

